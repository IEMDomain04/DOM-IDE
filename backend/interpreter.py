    def infer_type(self, node):
        if isinstance(node, NumNode):
            return 'int' if isinstance(node.value, int) else 'float'
        elif isinstance(node, StringNode):
            return 'string'
        elif isinstance(node, BoolNode):
            return 'bool'
        elif isinstance(node, RelOpNode):
            return 'bool'
        elif isinstance(node, LogOpNode):
            return 'bool'
        elif isinstance(node, NullNode):
            return 'null'
        elif isinstance(node, IdNode):
           if self.symbol_table.get_type(node.name):
               return self.symbol_table.get_type(node.name)
           else: return 'unknown'
        elif isinstance(node, BinOpNode):
            if node.op in ['<', '>', '<=', '>=', '==', '!=', '!', '&&', '||']:
                return 'bool'
            left = node.left
            right = node.right
            left_type = self.infer_type(left)
            right_type = self.infer_type(right)
            if left_type == right_type:
                return left_type
            else:
                if left_type == 'bool' and right_type == 'bool':
                    return 'bool'
                elif left_type == 'int' and right_type == 'bool':
                    return 'int'
                elif left_type == 'bool' and right_type == 'int':
                    return 'int'
                elif left_type == 'float' and right_type == 'bool':
                    return 'float'
                elif left_type == 'bool' and right_type == 'float':
                    return 'float'
                elif left_type == 'float' or right_type == 'float':
                    return 'float'
                elif left_type == 'int' or right_type == 'int':
                    return 'int'
                elif left_type == 'string' or right_type == 'string':
                    return 'string'
                else:
                    return 'unknown'
        elif isinstance(node, UnaryOpNode):
            return self.infer_type(node.expr)
        elif isinstance(node, ClanAccessNode):
            return self.symbol_table.get_type(node.name)
        elif isinstance(node, CurseCallNode):
            curse_node = self.symbol_table.get(node.name)
            if isinstance(curse_node, CurseDecNode):
                return curse_node.datatype
            return 'unknown'
        elif isinstance(node, str):
            return 'string'
        elif isinstance(node, bool):
            return 'bool'
        elif isinstance(node, int):
            return 'int'
        elif isinstance(node, float):
            return 'float'
        else:
            return 'unknown'

    def evaluate_node(self, node):
        if isinstance(node, NumNode):
            return node.value, None
        
        elif isinstance (node, StringNode):
            return node.value, None
        
        elif isinstance(node, BoolNode):
            return node.value, None
        
        elif isinstance(node, NullNode):
            return 'Null', None
        
        elif isinstance(node, IdNode):
            symbol = self.symbol_table.get(node.name)
            if symbol is None:
                return None, SemanticError(node.pos_start, node.pos_end, f"Variable '{node.name}' is not declared")
            if isinstance(symbol, VarDecNode):
                value, error = self.evaluate_node(symbol.value)
                if error:
                    return None, error
            elif isinstance(symbol, ClanDecNode):
                value = symbol.initial_values
                if isinstance(value, ClanLiteralNode):
                    value = value.values

            return value, None

        elif isinstance(node, (BinOpNode, RelOpNode, LogOpNode, ExponentNode)):
            # Check if this is inside a recursive function call
            inside_recursion = False
            true_parent = node.parent
            while true_parent and hasattr(true_parent, 'parent'):
                if isinstance(true_parent, CurseDecNode) and hasattr(node, 'left') and hasattr(node, 'right'):
                    # Check if either side contains a recursive call to the same function
                    if isinstance(node.left, CurseCallNode) and isinstance(node.right, CurseCallNode):
                        # If both sides call functions, we need isolation
                        inside_recursion = True
                        break
                true_parent = true_parent.parent

            # Only make a copy of scopes if we're in a recursive context
            if inside_recursion:
                original_scopes = copy.deepcopy(self.symbol_table.scopes)
            
            # Evaluate left side
            left_value, error = self.evaluate_node(node.left)
            if error:
                return None, error
            
            # Only restore scopes if needed
            if inside_recursion:
                self.symbol_table.scopes = copy.deepcopy(original_scopes)

            right_value, error = self.evaluate_node(node.right)
            if error:
                return None, error


            if isinstance(left_value, NumNode):
                left_value = left_value.value
            if isinstance(right_value, NumNode):
                right_value = right_value.value

            if left_value == 'Null' or right_value == 'Null':
                error = RTError(node.pos_start, node.pos_end, f"Invalid operation on 'null'")
                return None, error
            
            if not isinstance(node, ExponentNode):
                try:
                    def to_bool(val):
                                if isinstance(val, str):
                                    return True if val != "" else False
                                if isinstance(val, (int, float)):
                                    return val != 0
                                if isinstance(val, bool):
                                    return val
                                return bool(val)
                    
                    if left_value is not None and right_value is not None: 
                        # Convert True/False to 1/0 for arithmetic and comparison
                        if isinstance(left_value, bool):
                            left_value = 1 if left_value else 0
                        if isinstance(right_value, bool):
                            right_value = 1 if right_value else 0

                        if node.op == '+':
                            return left_value + right_value, None
                        elif node.op == '-':
                            result = left_value - right_value
                            print(f"Evaluating subtraction: {left_value} - {right_value} = {result}")
                            return result, None
                        elif node.op == '*':
                            return left_value * right_value, None
                        elif node.op == '/':
                            print(f"\n\n\n\nI REACHED HERE, RIGHT VALUE: {right_value}\n\n\n\n")
                            if right_value == 0 or right_value == 0.0:
                                return None, RTError(node.pos_start, node.pos_end, "Division by zero")
                            result = left_value / right_value
                            if result > 999999999:
                                return None, RTError(node.pos_start, node.pos_end, "Float significant values exceeded limit of 9 digits")
                            if isinstance(result, float):
                                decimal_part = str(result).split('.')[-1]
                                if len(decimal_part) > 7:
                                    result = round(result, 7)
                            return result, None
                        elif node.op == '%':
                            return left_value % right_value, None
                        elif node.op == '==':
                            return left_value == right_value, None
                        elif node.op == '!=':
                            return left_value != right_value, None
                        elif node.op == '<':
                            # Convert string operands to bool (1/0) for comparison
                            if isinstance(left_value, str):
                                left_value = 1 if left_value != "" else 0
                            if isinstance(right_value, str):
                                right_value = 1 if right_value != "" else 0
                            return left_value < right_value, None
                        elif node.op == '>':
                            if isinstance(left_value, str):
                                left_value = 1 if left_value != "" else 0
                            if isinstance(right_value, str):
                                right_value = 1 if right_value != "" else 0
                            return left_value > right_value, None
                        elif node.op == '<=':
                            if isinstance(left_value, str):
                                left_value = 1 if left_value != "" else 0
                            if isinstance(right_value, str):
                                right_value = 1 if right_value != "" else 0
                            return left_value <= right_value, None
                        elif node.op == '>=':
                            if isinstance(left_value, str):
                                left_value = 1 if left_value != "" else 0
                            if isinstance(right_value, str):
                                right_value = 1 if right_value != "" else 0
                            return left_value >= right_value, None
                        elif node.op == '&&':
                            return to_bool(left_value) and to_bool(right_value), None
                        elif node.op == '||':
                            return to_bool(left_value) or to_bool(right_value), None
                        else:
                            return None, RTError(node.pos_start, node.pos_end, f"Unknown operator '{node.op}'")
                    else:
                        return None, RTError(node.pos_start, node.pos_end, "Invalid operation on 'null'")

                except Exception as e:
                    return None, RTError(node.pos_start, node.pos_end, f"Error during operation '{node.op}': {str(e)}")
