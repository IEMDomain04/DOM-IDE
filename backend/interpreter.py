    def visit_BodyNode(self, node, parent):
        print(f"Visiting BodyNode")
        print(f"BodyNode Parent: {type(parent)}")
        self.symbol_table.push()  # Enter new scope for body
    
        for child in list(node.children):
            if isinstance(child, CurseDecNode):
                if self.symbol_table.get(child.name):
                    self.errors.append(SemanticError(child.pos_start, child.pos_end, f"Curse '{child.name}' already declared in this scope"))
                else:
                    self.symbol_table.set(child.name, child)

        self.visit_children(node)
        self.symbol_table.pop()  # Exit body scope
        print(f"Exiting BodyNode")

    def visit_CurseCallNode(self, node, parent):
        print(f"Visiting CurseCallNode with name: {node.name}")

        # Retrieve the curse declaration from the symbol table
        curse_dec_node = self.symbol_table.get(node.name)
        if curse_dec_node is None:
            self.error = SemanticError(node.pos_start, node.pos_end, f"Curse '{node.name}' is not declared")
            return None
        
        if curse_dec_node.datatype is not None:
            return # early return because this visit method is for void curse calls only so if it has a datatype, just ignore.

        # Evaluate arguments and map them to parameters
        self.symbol_table.push()  # Enter new scope for curse call
        try:
            for param, arg in zip(curse_dec_node.parameters, node.arguments):
                arg_value, error = self.evaluate_node(arg)
                if error:
                    self.error = error
                    return None

                print(f"Parameter '{param.name}' set to: {arg_value}")
                self.symbol_table.set(param.name, VarDecNode(False, param.datatype, param.name, NumNode(arg_value, None, None), param.pos_start, param.pos_end))

            self.visit(curse_dec_node.body, curse_dec_node)
            return
        except RecursionError:
            self.error = SemanticError(node.pos_start, node.pos_end, f"Recursion limit exceeded in curse '{node.name}'")
            return
        finally:
            self.symbol_table.pop()  # Exit the scope after the curse call

    def visit_InvokeNode(self, node, parent):
        print(f"Visiting InvokeNode")
        value = ''
        if isinstance(node.value, list):
            for list_item in node.value:
                temp, error = self.evaluate_node(list_item)
                if error:
                    self.error = error
                    break
                if isinstance(temp, str):
                    value += temp
                else: 
                    value += str(temp)
        else: 
            value, error = self.evaluate_node(node.value)
            if value is None:
                value = node.value
            if error:
                self.error = error
                return

        # Convert to string representation
        if hasattr(value, 'to_string'):
            output_text = value.to_string()
        else:
            output_text = str(value)
            
        # Add to accumulated output
        self.output.append(output_text)
        
        # Emit real-time update via socket
        if self.socketio:
            self.socketio.emit('output_update', {'output': output_text})
            
        print(f'Invocation: {output_text}')
        print(f"Exiting InvokeNode")

