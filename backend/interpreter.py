# > This class is responsible for interpreting the AST (Abstract Syntax Tree) generated by the parser.
# > Similarly to the semantic analyzer, it traverses the tree (pre-order) and executes the code represented by the nodes.
# > Each visit_<node_type> corresponds to a specific method for interpreting that node type.
# > Example: visit_InvokeNode has logic that will supposedly print what's in its node.value to the terminal.
#
# > Note: It has a special utility method "evaluate_node" that is used to evaluate the value of a node.
# > Example: if a node is a BinOpNode, it will evaluate the left and right nodes and apply the operator and return the result value.
# >          if a node is a CurseCallNode, it will evaluate the arguments and apply the curse's body logic, and return the result value.
# > Also supports nodes that are not directly executable, but rather represent an expression.
####################################

class DOMInterpreter: 
    def visit(self, node, parent=None):
        if hasattr(self, 'error') and self.error:
            return None 
    
        method_name = f'visit_{type(node).__name__}'
        visitor = getattr(self, method_name, self.generic_visit)
        return visitor(node, parent)

    def generic_visit(self, node, parent):
        if parent is None:
            print(f"Visiting root node: {type(node).__name__}")
        self.visit_children(node)

    def visit_children(self, node):
        for child in node.children:
            print(f"Child node: {type(child).__name__}, Parent node: {type(node).__name__}")
            self.visit(child, node)

